#!/usr/bin/env bash
set -euo pipefail

app_dir=/opt/listing-workbench
data_dir=/var/lib/listing-workbench
config_dir=/etc/listing-workbench
python_bin="$app_dir/.venv/bin/python"

sudo cloud-init status --wait
sudo apt-get update
sudo env DEBIAN_FRONTEND=noninteractive apt-get install -y ca-certificates curl python3-venv snapd tesseract-ocr tesseract-ocr-eng
if ! sudo snap list amazon-ssm-agent >/dev/null 2>&1; then
    sudo snap install amazon-ssm-agent --classic
fi
sudo snap start --enable amazon-ssm-agent

if ! id listing-workbench >/dev/null 2>&1; then
    sudo useradd --system --user-group --home-dir "$data_dir" --shell /usr/sbin/nologin listing-workbench
fi
sudo install -d -m 0755 "$app_dir"
sudo install -d -m 0700 -o listing-workbench -g listing-workbench "$data_dir"
sudo install -d -m 0700 "$config_dir"
sudo tar --no-same-owner -xzf /tmp/listing-workbench-runtime.tar.gz -C "$app_dir"
sudo python3 -m venv "$app_dir/.venv"
sudo "$python_bin" -m pip install --no-cache-dir -r "$app_dir/requirements.txt"

playwright_enabled=0
if [[ "${INSTALL_PLAYWRIGHT:-false}" == "true" ]]; then
    sudo "$python_bin" -m pip install --no-cache-dir 'playwright>=1.50,<2'
    sudo env "PLAYWRIGHT_BROWSERS_PATH=$app_dir/browsers" "$python_bin" -m playwright install --with-deps chromium
    playwright_enabled=1
fi
sudo install -m 0600 /dev/null "$config_dir/workbench.env"
printf 'LISTING_AMAZON_PLAYWRIGHT=%s\n' "$playwright_enabled" | sudo tee "$config_dir/workbench.env" >/dev/null
sudo install -m 0644 /tmp/listing-workbench.service /etc/systemd/system/listing-workbench.service
sudo systemctl daemon-reload
sudo systemctl enable --now listing-workbench.service

# Exercise the installed service before the image is captured.
curl --fail --silent --show-error --retry 12 --retry-connrefused --retry-delay 2 --max-time 10 \
    http://127.0.0.1:8000/openapi.json |
    "$python_bin" -c 'import json, sys; assert json.load(sys.stdin)["info"]["version"] == "1.3.2"'
curl --fail --silent --show-error --output /dev/null http://127.0.0.1:8000/
sudo systemctl stop listing-workbench.service
# Remove the empty database generated by the build-time check.
sudo rm -f "$data_dir/workbench.sqlite3" "$data_dir/workbench.sqlite3-wal" "$data_dir/workbench.sqlite3-shm"
rm -f /tmp/listing-workbench-runtime.tar.gz /tmp/listing-workbench.service
